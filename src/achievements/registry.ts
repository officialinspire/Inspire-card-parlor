export type AchievementCategory =
  | 'general'
  | 'klondike'
  | 'spider'
  | 'freecell'
  | 'war'
  | 'go-fish'
  | 'story'
  | 'collection'
  | 'exploration'
  | 'secrets';

export type AchievementRarity = 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary';

export interface AchievementDefinition {
  /** Stable id; never renamed once shipped (saves store it). */
  id: string;
  name: string;
  /** The unlock condition, as shown to the player. */
  description: string;
  /** Drawn medal glyph (see glyphs.ts). */
  icon: Glyph;
  category: AchievementCategory;
  rarity: AchievementRarity;
  xp: number;
  /** Secret: name and condition stay hidden until earned. */
  hidden?: boolean;
  /** Progress is `progress(facts)` out of `target`; earned when it reaches the target. */
  target: number;
  progress: (f: Facts) => number;
}


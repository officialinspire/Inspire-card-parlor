export const RARITY_XP: Record<AchievementRarity, number> = {
  common: 15,
  uncommon: 35,
  rare: 75,
  epic: 150,
  legendary: 300,
};

export const RARITY_LABEL: Record<AchievementRarity, string> = {
  common: 'Common',
  uncommon: 'Uncommon',
  rare: 'Rare',
  epic: 'Epic',
  legendary: 'Legendary',
};

type Def = [
  id: string,
  name: string,
  description: string,
  icon: Glyph,
  rarity: AchievementRarity,
  target: number,
  progress: (f: Facts) => number,
  hidden?: boolean,
];

const group = (category: AchievementCategory, defs: Def[]): AchievementDefinition[] =>
  defs.map(([id, name, description, icon, rarity, target, progress, hidden]) => ({
    id,
    name,
    description,
    icon,
    category,
    rarity,
    xp: RARITY_XP[rarity],
    target,
    progress,
    ...(hidden ? { hidden } : {}),
  }));

/** 1 when `cond`, else 0 (for yes/no achievements). */
const yes = (cond: boolean) => (cond ? 1 : 0);
/** Fastest win at or under `sec` seconds. */
const fast = (g: GameId, sec: number) => (f: Facts) => yes(f.fastest(g) <= sec);
const wins = (g?: GameId) => (f: Facts) => f.won(g);

